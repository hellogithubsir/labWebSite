def replace_html_texts(raw: str, mapping: dict[str, str]) -> str:
    # Replace only text/attribute values, never scripts or base64. Longest first
    # prevents a short phrase from corrupting a compound field.
    for old in sorted(mapping, key=len, reverse=True):
        raw = raw.replace(old, mapping[old])
    return raw


