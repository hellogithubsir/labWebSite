def insert_missing_sections(en_doc: Document):
    """Insert R-06 and A-04..A-08 before the corresponding existing headings."""
    zh_doc = Document(ZH_DOCX)
    zh_sections = section_table_map(zh_doc)
    en_body = en_doc.element.body
    # Existing target paragraphs in the English document.
    targets = {}
    for child in en_body.iterchildren():
        if not child.tag.endswith("}p"):
            continue
        p = Paragraph(child, en_doc)
        text = norm(p.text)
        m = SECTION_RE.search(text)
        if m and m.group(1) in {"P-01", "N-01"}:
            targets[m.group(1)] = child

    for group, before in [(["R-06"], "P-01"), (["A-04", "A-05", "A-06", "A-07", "A-08"], "N-01")]:
        elements = []
        for section in group:
            source_heading = None
            for child in zh_doc.element.body.iterchildren():
                if not child.tag.endswith("}p"):
                    continue
                p = Paragraph(child, zh_doc)
                if SECTION_RE.search(norm(p.text)) and SECTION_RE.search(norm(p.text)).group(1) == section:
                    source_heading = child
                    break
            if source_heading is None:
                raise RuntimeError(f"Missing source heading {section}")
            heading = copy.deepcopy(source_heading)
            # Set heading text deterministically while preserving style.
            for node in xpath_nodes(heading, ".//w:t"):
                node.text = MISSING_EN[section]["heading"]
            elements.append(heading)
            # Find the source table belonging to this section.
            source_table = zh_sections[section][0]
            table = copy.deepcopy(source_table._element)
            ns = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main"}
            rows = MISSING_EN[section]["rows"]
            cells = xpath_nodes(table, ".//w:tc")
            expected = sum(len(row) for row in rows)
            if len(cells) < expected:
                raise RuntimeError(f"Unexpected table shape for {section}: {len(cells)} < {expected}")
            pos = 0
            for row in rows:
                for value in row:
                    tc = cells[pos]
                    pos += 1
                    text_nodes = xpath_nodes(tc, ".//w:t")
                    if text_nodes:
                        text_nodes[0].text = value
                        for extra in text_nodes[1:]:
                            extra.text = ""
                    else:
                        run = etree.SubElement(etree.SubElement(tc, f"{{{ns['w']}}}p"), f"{{{ns['w']}}}r")
                        etree.SubElement(run, f"{{{ns['w']}}}t").text = value
            elements.append(table)
        target = targets[before]
        # ``addprevious`` inserts immediately before the target. Iterating in
        # source order therefore preserves the mother-document order
        # A-04 → A-05 → A-06 → A-07 → A-08.
        for element in elements:
            target.addprevious(element)


def set_docx_table_grid(table, widths: tuple[int, ...]) -> None:
    """Apply deterministic fixed-width geometry to one output table."""
    if len(widths) != len(table.columns):
        raise RuntimeError(f"Table width count mismatch: {len(widths)} != {len(table.columns)}")
    total = sum(widths)
    table.autofit = False
    tbl_pr = table._tbl.tblPr
    tbl_w = tbl_pr.find(qn("w:tblW"))
    if tbl_w is None:
        tbl_w = OxmlElement("w:tblW")
        tbl_pr.insert(0, tbl_w)
    tbl_w.set(qn("w:w"), str(total))
    tbl_w.set(qn("w:type"), "dxa")
    layout = tbl_pr.find(qn("w:tblLayout"))
    if layout is None:
        layout = OxmlElement("w:tblLayout")
        tbl_pr.append(layout)
    layout.set(qn("w:type"), "fixed")

    grid = table._tbl.tblGrid
    for child in list(grid):
        grid.remove(child)
    for width in widths:
        column = OxmlElement("w:gridCol")
        column.set(qn("w:w"), str(width))
        grid.append(column)
    for row in table.rows:
        for index, cell in enumerate(row.cells):
            tc_pr = cell._tc.get_or_add_tcPr()
            tc_w = tc_pr.find(qn("w:tcW"))
            if tc_w is None:
                tc_w = OxmlElement("w:tcW")
                tc_pr.insert(0, tc_w)
            tc_w.set(qn("w:w"), str(widths[index]))
            tc_w.set(qn("w:type"), "dxa")


