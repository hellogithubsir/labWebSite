def normalize_docx_row_heights(doc: Document) -> None:
    """Keep OOXML row heights integer-valued for Office CLI compatibility."""
    for node in xpath_nodes(doc.element.body, ".//w:trHeight"):
        raw_value = node.get(qn("w:val"))
        if raw_value is None:
            continue
        try:
            numeric = float(raw_value)
        except ValueError:
            continue
        if not numeric.is_integer():
            node.set(qn("w:val"), str(int(round(numeric))))


